package net.jamnig.breakalert.services;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.restclient.RestTemplateBuilder;
import org.springframework.http.*;
import org.springframework.stereotype.Service;
import org.springframework.web.client.HttpClientErrorException;
import org.springframework.web.client.RestClientException;
import org.springframework.web.client.RestTemplate;

import java.util.List;

@Slf4j
@Service
@RequiredArgsConstructor
public class LlmApiService {
    private final RestTemplateBuilder restTemplateBuilder;

    @Value("${llm.api.url:https://api.openai.com/v1/chat/completions}")
    private String apiUrl;

    @Value("${llm.api.key:}")
    private String apiKey;

    @Value("${llm.api.model:gpt-5-mini-2025-08-07}")
    private String modelName;

    private static final String SYSTEM_PROMPT = "You are an assistant which analyzes the changes from APIs over time written in markdown. " +
            "Describe the most important/meaningful changes as briefly as you can. " +
            "The result should be a general textual overview of the changes including endpoint paths. Do not go into detail or make an enumeration. " +
            "The receiver of your answer is a developer, so there is no need for explanations on 'easy' topics but still keep it simple. " +
            "Make line breaks after sentences for a better structure. But do not make double line breaks.";

    public String generateResponse(String prompt) {
        log.info("Requesting API change summary from LLM (Model: {}, URL: {})", modelName, apiUrl);

        RestTemplate restTemplate = restTemplateBuilder.build();
        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);

        // Only set Bearer token if an API key is provided (Local LLMs like Ollama don't need one)
        if (apiKey != null && !apiKey.isBlank()) {
            headers.setBearerAuth(apiKey);
        }

        LlmRequest requestBody = new LlmRequest(modelName, List.of(
                new Message("system", SYSTEM_PROMPT),
                new Message("user", prompt)
        ));

        HttpEntity<LlmRequest> requestEntity = new HttpEntity<>(requestBody, headers);

        try {
            ResponseEntity<LlmResponse> response = restTemplate.exchange(
                    apiUrl,
                    HttpMethod.POST,
                    requestEntity,
                    LlmResponse.class
            );

            if (response.getBody() != null && !response.getBody().choices().isEmpty()) {
                log.info("Successfully generated LLM summary.");
                return response.getBody().choices().get(0).message().content();
            }

            log.warn("Received empty choices array from LLM provider.");
            return "Warning: No summary was generated by the LLM.";

        } catch (HttpClientErrorException.TooManyRequests e) {
            log.error("LLM Quota/Rate limit exceeded: {}", e.getResponseBodyAsString());
            return "API quota or rate limit exceeded. Could not generate summary.";
        } catch (HttpClientErrorException e) {
            log.error("LLM API client error ({}): {}", e.getStatusCode(), e.getResponseBodyAsString());
            return "Error communicating with the LLM provider.";
        } catch (RestClientException e) {
            log.error("Failed to connect to LLM API: {}", e.getMessage());
            return "Error connecting to the LLM API.";
        }
    }

    public record LlmRequest(String model, List<Message> messages) {}
    public record Message(String role, String content) {}
    public record LlmResponse(List<Choice> choices) {}
    public record Choice(Message message) {}
}

